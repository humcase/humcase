// The shadcn/ui Sidebar primitives Humcase uses: a fixed bar (no collapsing, no mobile sheet,
// no keyboard toggle; the `.workspace-app` grid places it and the app has its own narrow drawer).

const SIDEBAR_WIDTH = "16rem"

function SidebarProvider({ className, style, children, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="sidebar-wrapper"
      style={{ "--sidebar-width": SIDEBAR_WIDTH, ...style } as React.CSSProperties}
      className={cn("group/sidebar-wrapper flex min-h-svh w-full", className)}
      {...props}
    >
      {children}
    </div>
  )
}

function Sidebar({ className, children, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="sidebar"
      className={cn(
        "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
        className
      )}
      {...props}
    >
      {children}
    </div>
  )
}

